package app

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/bakanura/gjallarOS/internal/installer/config"
	"github.com/bakanura/gjallarOS/internal/installer/discovery"
)

func TestRequireNixOS(t *testing.T) {
	path := filepath.Join(t.TempDir(), "os-release")
	os.WriteFile(path, []byte("ID=nixos\n"), 0644)
	if err := requireNixOS(path); err != nil {
		t.Fatal(err)
	}
	os.WriteFile(path, []byte("ID=other\n"), 0644)
	if err := requireNixOS(path); err == nil {
		t.Fatal("accepted non-NixOS")
	}
}

func TestNormalizePreset(t *testing.T) {
	u := config.User{Username: "alice", KeyboardLayout: "de-latin1", WorkUserEnable: true}
	normalizePreset(&u, "/repo")
	if u.DotfilesDir != "/home/alice/Documents/gjallarOS" || u.WorkUsername != "alice-corp" || u.KeyboardLayout != "de" {
		t.Fatalf("%+v", u)
	}
}

func TestExistingInstallMarkers(t *testing.T) {
	root := t.TempDir()
	path := filepath.Join(root, "settings.nix")
	os.WriteFile(path, []byte("# Generated by gjallarctl; do not edit\n"), 0644)
	if !existingInstall(root) {
		t.Fatal("new marker not detected")
	}
}

func TestValidateSelections(t *testing.T) {
	o := discovery.Options{Profiles: []string{"laptop"}, Shells: []string{"zsh"}, Editors: []string{"vscodium"}, Browsers: []string{"librewolf"}, Themes: []string{"catppuccin"}}
	u := config.User{Profile: "laptop", Shell: "zsh", Editors: []string{"vscodium"}, Browsers: []string{"librewolf"}, Theme: "catppuccin", DotfilesDir: "/repo"}
	if err := validateSelections(u, o); err != nil {
		t.Fatal(err)
	}
	u.Profile = "../../bad"
	if err := validateSelections(u, o); err == nil {
		t.Fatal("accepted invalid profile")
	}
}
